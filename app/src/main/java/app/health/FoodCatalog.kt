 /* Средняя порция по категории — для своих блюд, которых нет в справочнике. */
 @JvmField val KCAL_CATEGORY = mapOf(
  "McDonald’s" to 400, "Быстрая еда" to 450, "Домашние блюда" to 380,
  "Молочное" to 150, "Мясо и рыба" to 300, "Напитки" to 110,
