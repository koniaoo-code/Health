 private fun homeCombo(name: String): Int? {
  val i = name.indexOf(" с ")
  if (i <= 0) return null
  val base = KCAL_HOME_BASE[name.substring(0, i).trim()] ?: return null
  val add = KCAL_HOME_ADD[name.substring(i + 3).trim()] ?: return null
  return base + add
 }

 private fun bestMatch(mealName: String): Int? {
  KCAL_ITEM[mealName]?.let { return it }
  val dish = dishName(mealName)
  KCAL_ITEM[dish]?.let { return it }
  homeCombo(dish)?.let { return it }
  val d = dish.lowercase()
  var found: Int? = null
  var bestLen = 0
  for ((key, value) in KCAL_ITEM) {
   val k = key.lowercase()
   val hit = d.startsWith(k) || (k.startsWith(d) && d.length >= 5)
   if (hit && key.length > bestLen) {
    bestLen = key.length
    found = value
   }
  }
  return found
 }

 /** Оценка калорий по названию и размеру порции: S −30 %, M — как в справочнике, L +50 %. */
 fun kcal(mealName: String, size: String): Int {
  var v = bestMatch(mealName) ?: KCAL_CATEGORY[categoryName(mealName)] ?: KCAL_CATEGORY.values.sum() / KCAL_CATEGORY.size
  if (size.equals("s", true)) v = Math.round(v * 0.7).toInt()
  if (size.equals("l", true)) v = Math.round(v * 1.5).toInt()
  return v
 }

 /** Подпись «откуда число» — для деталей записи. */
 fun kcalSource(mealName: String): String {
  val dish = dishName(mealName)
  val category = categoryName(mealName)
  if (KCAL_ITEM.containsKey(mealName)) return "фирменная порция сети"
  if (KCAL_ITEM.containsKey(dish)) return "точное блюдо справочника"
  if (homeCombo(dish) != null) return "блюдо справочника: база + добавка"
  if (bestMatch(dish) != null) return "похожее блюдо справочника"
  val cat = category ?: dish
  return if (KCAL_CATEGORY.containsKey(cat)) "среднее по категории «$cat»"
  else "среднее по всему справочнику"
 }

 private fun dishName(mealName: String): String {
  val p = mealName.split(" · ", limit = 2)
  return if (p.size >= 2) p[1].trim() else mealName.trim()
 }

 private fun categoryName(mealName: String): String? {
  val p = mealName.split(" · ", limit = 2)
  return if (p.size >= 2) p[0].trim() else null
 }
